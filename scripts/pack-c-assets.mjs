#!/usr/bin/env node
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');
const DIST_DIR = path.join(ROOT_DIR, 'dist');
const PKG_FILE = path.join(ROOT_DIR, 'package.json');
const OUT_FILE = path.join(ROOT_DIR, 'src', 'native', 'embedded_assets.h');

const MIME_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8',
  '.mjs': 'application/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.ico': 'image/x-icon',
  '.txt': 'text/plain; charset=utf-8',
  '.wasm': 'application/wasm',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2',
};

function getMimeType(filePath) {
  const ext = path.extname(filePath).toLowerCase();
  return MIME_TYPES[ext] || 'application/octet-stream';
}

function collectFiles(dir, baseDir = dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const results = [];

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...collectFiles(fullPath, baseDir));
    } else if (entry.isFile()) {
      const rel = path.relative(baseDir, fullPath).split(path.sep).join('/');
      results.push({ fullPath, urlPath: `/${rel}` });
    }
  }

  return results.sort((a, b) => a.urlPath.localeCompare(b.urlPath));
}

function minifyAssetBuffer(filePath, rawBuffer) {
  const ext = path.extname(filePath).toLowerCase();

  if (ext === '.html') {
    const raw = rawBuffer.toString('utf8');
    const minified = raw
      .replace(/<!--[\s\S]*?-->/g, '')
      .replace(/>\s+</g, '><')
      .replace(/\s{2,}/g, ' ')
      .trim();
    return Buffer.from(minified, 'utf8');
  }

  if (ext === '.svg') {
    const raw = rawBuffer.toString('utf8');
    const minified = raw
      .replace(/<!--[\s\S]*?-->/g, '')
      .replace(/>\s+</g, '><')
      .replace(/\s{2,}/g, ' ')
      .trim();
    return Buffer.from(minified, 'utf8');
  }

  if (ext === '.json') {
    try {
      const parsed = JSON.parse(rawBuffer.toString('utf8'));
      return Buffer.from(JSON.stringify(parsed), 'utf8');
    } catch {
      return rawBuffer;
    }
  }

  return rawBuffer;
}

function formatByteArray(buffer, symbolName) {
  if (buffer.length === 0) {
    return `static const unsigned char ${symbolName}[1] = { 0x00 };\n`;
  }

  const lines = [`static const unsigned char ${symbolName}[${buffer.length}] = {`];
  const bytesPerLine = 16;

  for (let i = 0; i < buffer.length; i += bytesPerLine) {
    const slice = buffer.subarray(i, Math.min(i + bytesPerLine, buffer.length));
    const hex = Array.from(slice, (b) => `0x${b.toString(16).padStart(2, '0')}`).join(', ');
    const suffix = i + bytesPerLine < buffer.length ? ',' : '';
    lines.push(`  ${hex}${suffix}`);
  }

  lines.push('};\n');
  return lines.join('\n');
}

function escapeCString(value) {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

function readAppVersion() {
  try {
    const pkg = JSON.parse(fs.readFileSync(PKG_FILE, 'utf8'));
    if (pkg.version && pkg.version !== '0.0.0') {
      return String(pkg.version);
    }
  } catch {
    // Fallback below
  }
  return '1.0.0';
}

function main() {
  const indexHtml = path.join(DIST_DIR, 'index.html');
  if (!fs.existsSync(indexHtml)) {
    console.error('Error: dist/index.html not found. Run "npm run build" first.');
    process.exit(1);
  }

  const files = collectFiles(DIST_DIR);
  if (files.length === 0) {
    console.error('Error: No files found inside dist/.');
    process.exit(1);
  }

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });

  const appVersion = readAppVersion();
  const builtAt = new Date().toISOString();
  const buildHash = crypto.createHash('sha256');

  const processed = files.map((file) => {
    const rawBuffer = fs.readFileSync(file.fullPath);
    const minBuffer = minifyAssetBuffer(file.fullPath, rawBuffer);
    if (minBuffer.length < rawBuffer.length) {
      fs.writeFileSync(file.fullPath, minBuffer);
    }
    buildHash.update(file.urlPath);
    buildHash.update(minBuffer);
    return {
      urlPath: file.urlPath,
      mimeType: getMimeType(file.fullPath),
      buffer: minBuffer,
      rawBytes: rawBuffer.length,
    };
  });

  const buildId = buildHash.digest('hex').slice(0, 12);

  const headerParts = [
    '/* Auto-generated by scripts/pack-c-assets.mjs. Do not edit manually. */',
    '#ifndef VERIHASH_EMBEDDED_ASSETS_H',
    '#define VERIHASH_EMBEDDED_ASSETS_H',
    '',
    '#include <stddef.h>',
    '',
    `#define VERIHASH_APP_VERSION "${escapeCString(appVersion)}"`,
    `#define VERIHASH_BUILD_ID "${escapeCString(buildId)}"`,
    `#define VERIHASH_BUILT_AT "${escapeCString(builtAt)}"`,
    '',
    'typedef struct {',
    '  const char *path;',
    '  const char *mime_type;',
    '  const unsigned char *data;',
    '  size_t length;',
    '  int immutable;',
    '} VerihashAsset;',
    '',
  ];

  const tableEntries = [];
  let totalRawBytes = 0;
  let totalMinBytes = 0;

  processed.forEach((item, idx) => {
    const symbolName = `verihash_asset_${idx}`;
    const isImmutable = item.urlPath.startsWith('/assets/') ? 1 : 0;

    totalRawBytes += item.rawBytes;
    totalMinBytes += item.buffer.length;
    headerParts.push(`/* ${item.urlPath} (${item.buffer.length} bytes) */`);
    headerParts.push(formatByteArray(item.buffer, symbolName));

    tableEntries.push(
      `  { "${escapeCString(item.urlPath)}", "${escapeCString(item.mimeType)}", ${symbolName}, (size_t)${item.buffer.length}, ${isImmutable} }`
    );
  });

  headerParts.push('static const VerihashAsset VERIHASH_ASSETS[] = {');
  headerParts.push(tableEntries.join(',\n'));
  headerParts.push('};');
  headerParts.push('');
  headerParts.push(`#define VERIHASH_ASSET_COUNT ${processed.length}u`);
  headerParts.push('');
  headerParts.push('#endif /* VERIHASH_EMBEDDED_ASSETS_H */');
  headerParts.push('');

  fs.writeFileSync(OUT_FILE, headerParts.join('\n'), 'utf8');

  console.log(
    `Minified & packed ${processed.length} asset(s) (${(totalRawBytes / 1024).toFixed(1)} KiB -> ${(totalMinBytes / 1024).toFixed(1)} KiB, buildId=${buildId}) into src/native/embedded_assets.h`
  );
}

main();
